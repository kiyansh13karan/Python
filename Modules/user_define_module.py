# User defined module in python :-

'''
A user-defined module is a Python file (with a .py extension) that you create yourself. It contains functions, classes, or variables that you can use in other Python programs by importing the file.

This helps make your code:
Reusable ✅
Organized 📦
Clean and modular 🧩
'''


#  Example: Creating a User-Defined Module : -
# mymodule.py

def greet(name):
    return f"Hello, {name}!"

def add(x, y):
    return x + y
